#!/usr/bin/env python3
"""Generate the SEIS 201 Unit 1 HW Case B lift-station artifacts.

All organizations, people, equipment, specifications, and measurements in this
case are fictional. Values are instructional and are not verified by a licensed
engineer.

The deterministic seed is intentionally documented so instructors can reproduce
the student data and answer key exactly.
"""

from __future__ import annotations

import csv
import random
import statistics
from datetime import datetime, timedelta
from pathlib import Path


SEED = 201_01_07
READINGS_PER_CHANNEL = 12
BASELINE_PSIG = 42.00
TOLERANCE_PSIG = 0.75
PLANTED_CHANNEL = "PT-107"
PLANTED_OFFSET_PSIG = 4.80
CHANNELS = [f"PT-{channel}" for channel in range(101, 109)]

ROOT = Path(__file__).resolve().parents[2]
OUTPUT_DIR = ROOT / "teaching-pack" / "07-HW-CASE-B-LIFT-STATION"
STUDENT_DIR = OUTPUT_DIR / "student"
INSTRUCTOR_DIR = OUTPUT_DIR / "instructor"


def generate_readings() -> dict[str, list[float]]:
    rng = random.Random(SEED)
    readings: dict[str, list[float]] = {}
    for channel in CHANNELS:
        center = BASELINE_PSIG
        if channel == PLANTED_CHANNEL:
            center += PLANTED_OFFSET_PSIG
        readings[channel] = [
            round(rng.gauss(center, 0.07), 2)
            for _ in range(READINGS_PER_CHANNEL)
        ]
    return readings


def write_csv(readings: dict[str, list[float]]) -> None:
    start = datetime(2028, 9, 16, 10, 20)
    path = STUDENT_DIR / "sensors_startup.csv"
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            ["channel_id", "reading_index", "value", "units", "timestamp"]
        )
        for index in range(READINGS_PER_CHANNEL):
            timestamp = start + timedelta(seconds=30 * index)
            for channel in CHANNELS:
                writer.writerow(
                    [
                        channel,
                        index + 1,
                        f"{readings[channel][index]:.2f}",
                        "psig",
                        timestamp.isoformat(timespec="seconds"),
                    ]
                )


def write_foreman_report(grand_average: float) -> None:
    deviation = grand_average - BASELINE_PSIG
    report = f"""# ACMEJOB.Ai | FOREMAN v4.2

## Automated startup acceptance report

**Client:** Westfield Public Works  
**Facility:** Oak Street Lift Station  
**System:** Force-main / wet-well discharge header pressure instrumentation  
**Run:** Standby equalization check, 2028-09-16  
**Result:** **PASS**

FOREMAN v4.2 processed 96 pressure observations from eight installed
transducers. The grand average was **{grand_average:.2f} psig**, a deviation of
**{deviation:+.2f} psig** from the expected 42.00 psig standby baseline.

Acceptance limit: ±0.75 psig per WP-LS-3 §2.1. Because the reported deviation is
within ±0.75 psig, the instrument set is accepted for startup.

No per-channel exception table was generated.

---

**AUTOMATED DISPOSITION: PASS**  
Generated by FOREMAN v4.2 for ACMEJOB.Ai

Training artifact only. WP-LS-3 is fictional. Invented data; not verified by a
licensed engineer.
"""
    (STUDENT_DIR / "FOREMAN_PASS_report.md").write_text(report, encoding="utf-8")


