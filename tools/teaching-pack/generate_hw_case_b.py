def write_instructor_key(
    readings: dict[str, list[float]], means: dict[str, float], grand_average: float
) -> None:
    good_channels = [
        value
        for channel, values in readings.items()
        if channel != PLANTED_CHANNEL
        for value in values
    ]
    good_average = statistics.mean(good_channels)
    planted_sd = statistics.stdev(readings[PLANTED_CHANNEL])
    diluted_bias = grand_average - good_average

    table_rows = "\n".join(
        f"| {channel} | {means[channel]:.3f} | "
        f"{means[channel] - BASELINE_PSIG:+.3f} | "
        f"{'FAIL' if abs(means[channel] - BASELINE_PSIG) > TOLERANCE_PSIG else 'PASS'} |"
        for channel in CHANNELS
    )

    key = f"""# Instructor key — HW Case B: Oak Street Lift Station

**Do not distribute with the student package.**

## Planted condition

- Bad channel: **{PLANTED_CHANNEL}**
- Planted systematic offset: **+{PLANTED_OFFSET_PSIG:.2f} psig**
- Expected standby baseline: **{BASELINE_PSIG:.2f} psig**
- Fictional requirement: WP-LS-3 §2.1, **each channel** within
  ±{TOLERANCE_PSIG:.2f} psig under the defined standby condition
- {PLANTED_CHANNEL} sample mean: **{means[PLANTED_CHANNEL]:.3f} psig**
- {PLANTED_CHANNEL} sample standard deviation: **{planted_sd:.3f} psig**

The bad channel's readings are tightly grouped, so the channel is **precise but
inaccurate**. The offset is systematic; its small reading-to-reading scatter is
random variation.

## Reproducible results

| Channel | Mean (psig) | Error from 42.00 (psig) | Per-channel result |
|---|---:|---:|---|
{table_rows}

The mean of all 96 observations is **{grand_average:.3f} psig** (FOREMAN rounds
to **{grand_average:.2f} psig**), or
**{grand_average - BASELINE_PSIG:+.3f} psig** versus the baseline. That numeric
calculation is correct.

The seven unaffected channels average **{good_average:.3f} psig**. Giving each
channel equal weight dilutes one channel's roughly +4.8 psig bias by a factor of
eight, leaving only about **{diluted_bias:+.3f} psig** in the grand average.
That falls inside ±0.75 psig even though {PLANTED_CHANNEL} itself fails badly.
FOREMAN applied an array-level average to a per-channel requirement, so its PASS
method and disposition are wrong.

## Buried clue

The technician-notes section of `install_startup_note.md` says a local zero trim
showing +4.8 psi correction was used on PT-107 while its equalization valve was
shut. Students should find this only after examining the data and then returning
to the field record. It supports, but does not replace, the statistical evidence
of systematic error.

## What a good student write-up includes

1. **Requirement:** quotes or paraphrases “each channel,” the 42.00 psig defined
   standby baseline, and the ±0.75 psig limit.
2. **Evidence:** calculates per-channel means and a scatter measure or range;
   identifies PT-107 as tight but high.
3. **Diagnosis:** distinguishes its random scatter from systematic offset and
   uses “precise but inaccurate” correctly.
4. **Judgment:** rejects FOREMAN's PASS even though its arithmetic is correct;
   explains why averaging across channels answers the wrong question.
5. **Action:** holds acceptance, checks PT-107 zero/manifold/configuration
   against a traceable reference, corrects or replaces it, and repeats the
   defined standby test for every channel. Students should not simply delete the
   outlier and proceed.
6. **Decision log:** records the requirement, dataset/version, calculations,
   anomaly, field-note clue, decision owner, hold/retest action, and unresolved
   uncertainty. Diane, not FOREMAN, owns engineering acceptance.

Reasonable uncertainty discussions may mention reference-gauge uncertainty,
resolution, repeatability, stabilization, and whether the ±0.75 psig criterion
is an acceptance limit rather than a statistical confidence interval.

---

Fictional instructional case. Data generated with seed {SEED}. Not verified by
a licensed engineer.
"""
    (INSTRUCTOR_DIR / "INSTRUCTOR_KEY.md").write_text(key, encoding="utf-8")


def main() -> None:
    STUDENT_DIR.mkdir(parents=True, exist_ok=True)
    INSTRUCTOR_DIR.mkdir(parents=True, exist_ok=True)

    readings = generate_readings()
    means = {
        channel: statistics.mean(values) for channel, values in readings.items()
    }
    grand_average = statistics.mean(
        value for values in readings.values() for value in values
    )

    write_csv(readings)
    write_foreman_report(grand_average)
    write_startup_note()
    write_student_ask()
    write_readme()
    write_instructor_key(readings, means, grand_average)

    print(f"Wrote HW Case B artifacts to {OUTPUT_DIR}")
    for channel in CHANNELS:
        print(f"{channel}: mean={means[channel]:.3f} psig")
    print(f"Grand average: {grand_average:.3f} psig")


if __name__ == "__main__":
    main()
